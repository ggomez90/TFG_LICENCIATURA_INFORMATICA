export async function seedLocalidad(prisma: PrismaClient) {
  // 1) Placeholder para provincias sin localidades cargadas (todas menos SANTA FE)
  const provincias = await prisma.provincia.findMany({ orderBy: { idProvincia: 'asc' } });
  const placeholders = provincias
    .filter((p) => p.idProvincia !== ID_SANTA_FE)
    .map((p) => ({
      idLocalidad: 900000 + p.idProvincia, // id ficticio para no chocar
      nombre: 'LOCALIDADES NO DISPONIBLE',
      idProvincia: p.idProvincia,
    }));

  // 2) Localidades de Santa Fe con ids secuenciales a partir de 210000
  const baseId = 210000;
  const santaFe = SANTA_FE_LOCALIDADES.map((nombre, idx) => ({
    idLocalidad: baseId + idx,
    nombre,
    idProvincia: ID_SANTA_FE,
  }));

  await prisma.localidad.createMany({
    data: [...placeholders, ...santaFe],
    skipDuplicates: true,
  });
}
